import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire('C:/Users/mattp/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/package.json');
const {chromium}=require('playwright');
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1280,height:800}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:4173');
const fixture=await page.evaluate(async()=>{const {createGame,saveGame}=await import('/game/engine.js');const s=createGame('Mara');s.mode='battle';s.enemy={name:'Royal bailiff',hp:100,maxHp:100,attack:12,gold:15,guard:true,weakness:'quick strikes'};return saveGame(s);});
await page.addInitScript(value=>localStorage.setItem('crownstealer-save-v1',value),fixture);
await page.reload();
await page.evaluate(async()=>{const {AudioDirector}=await import('/game/audio.js');const original=AudioDirector.prototype.effect;window.sounds=[];AudioDirector.prototype.effect=function(name){window.sounds.push(name);return original.call(this,name);};});
await page.locator('#continue-game').click();
await page.getByRole('button',{name:'⚔ Strike',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('#scene-caption').textContent.startsWith('Your strike:'));
assert.equal(await page.locator('#actions').getAttribute('aria-busy'),'true');
await page.screenshot({path:'artifacts/combat-strike.png'});
await page.waitForFunction(()=>window.sounds.includes('hurt'));
await page.screenshot({path:'artifacts/combat-counter.png'});
await page.waitForFunction(()=>!document.querySelector('#actions').hasAttribute('aria-busy'));
assert.deepEqual((await page.evaluate(()=>window.sounds)).slice(0,2),['hit','hurt']);
await page.getByRole('button',{name:'Guard',exact:true}).click();
await page.waitForFunction(()=>window.sounds.includes('block'));
await page.evaluate(()=>window.dispatchEvent(new Event('androidpause')));
assert.equal(await page.locator('#actions').getAttribute('aria-busy'),null);
await page.evaluate(()=>window.dispatchEvent(new Event('androidresume')));
await page.emulateMedia({reducedMotion:'reduce'});
await page.setViewportSize({width:412,height:915});
await page.getByRole('button',{name:'Ember spell · 3 food',exact:true}).click();
await page.waitForFunction(()=>window.sounds.includes('magic'));
await page.screenshot({path:'artifacts/combat-phone.png'});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.waitForFunction(()=>!document.querySelector('#actions').hasAttribute('aria-busy'));
assert.deepEqual(errors,[]);await browser.close();console.log('Combat browser: ordered sounds, locked turn, native pause, reduced motion and phone layout pass.');
