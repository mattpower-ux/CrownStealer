import {readFileSync, writeFileSync} from 'node:fs';
import {REGIONAL_PATTERNS} from '../public/game/regional-gladiator-patterns.js';

// Run after approved roster edits; artwork/status metadata stays in the editor.
const source = JSON.parse(readFileSync(new URL('../public/game/gladiator-roster-editor-data.json', import.meta.url)));
const rosters = Object.fromEntries(source.arenas.filter(a => a.id !== 'bellwether').map(arena => {
  if (arena.fighters.length !== 10 || REGIONAL_PATTERNS[arena.id]?.length !== 10) throw new Error(`Incomplete roster: ${arena.id}`);
  return [arena.id, arena.fighters.map(f => {
    const steps = REGIONAL_PATTERNS[arena.id][f.bout - 1];
    const kind = steps.some(s => s.armor) ? 'armored' : steps.some(s => s.blows.length > 1) ? 'swift' : 'brute';
    return {id: `${arena.id}-${String(f.bout).padStart(2, '0')}`, name: f.name, weapon: f.weapon,
      description: f.look, kind, weakness: kind === 'armored' ? 'quick strikes' : 'guard then counter',
      portrait: `/assets/gladiator-${arena.id}-${String(f.bout).padStart(2, '0')}.webp`, steps};
  })];
}));
writeFileSync(new URL('../public/game/regional-gladiators.js', import.meta.url),
  '// Generated by scripts/generate-regional-gladiators.mjs from the approved editor roster.\n' +
  `export const REGIONAL_GLADIATORS = ${JSON.stringify(rosters, null, 2)};\n` +
  'export const REGIONAL_GLADIATOR_BY_ID = Object.fromEntries(Object.values(REGIONAL_GLADIATORS).flat().map(f => [f.id, f]));\n');
console.log(`Generated ${Object.values(rosters).flat().length} regional gladiators.`);
